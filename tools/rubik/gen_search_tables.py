#!/usr/bin/env python3
"""Derive quarter-turn and exact radius-five tables from the original C data.

Host-only generator, not part of target execution or the normal build.
The C solver and its input tables remain unchanged.
"""
from collections import deque
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[2]


def source_tables():
    source = (ROOT / "src/rubik/solver_tables.inc").read_text()
    transitions = []
    tables = []
    for name, count in (("perm_next", 5040), ("ori_next", 729)):
        body = re.search(
            rf"{name}\[{count}\]\[9\] = \{{(.*?)\n\}};", source, re.S
        )[1]
        values = list(map(int, re.findall(r"\d+", body)))
        assert len(values) == count * 9
        rows = [values[i:i + 9] for i in range(0, len(values), 9)]
        for state, row in enumerate(rows):
            for move in (0, 3, 6):
                successor = state
                for turn in range(3):
                    successor = rows[successor][move]
                    assert successor == row[move + turn]
                assert rows[successor][move] == state
        transitions.append(rows)
        tables.append((name, "half", [row[m] for row in rows for m in (0, 3, 6)]))
    for name, count in (("perm_dist", 5040), ("ori_dist", 729)):
        body = re.search(rf"{name}\[{count}\] = \{{(.*?)\n\}};", source, re.S)[1]
        values = list(map(int, re.findall(r"\d+", body)))
        assert len(values) == count
        tables.append((name, "byte", values))
    return transitions, tables


def radius_five(pn, on):
    # Edges have unit cost, and every move's inverse is in the move set.
    # BFS from solved therefore gives exact solution lengths in this ball.
    distances = {0: 0}
    queue = deque([0])
    while queue:
        key = queue.popleft()
        distance = distances[key]
        if distance == 5:
            continue
        p, o = divmod(key, 729)
        for np, no in zip(pn[p], on[o]):
            successor = np * 729 + no
            if successor not in distances:
                distances[successor] = distance + 1
                queue.append(successor)
    assert len(distances) == 12224
    return distances


def generate():
    (pn, on), tables = source_tables()
    distances = radius_five(pn, on)
    records, offsets = [], []
    for p in range(5040):
        offsets.append(len(records))
        for o in range(729):
            distance = distances.get(p * 729 + o)
            if distance is None:
                continue
            move = 15 if distance == 0 else next(
                m for m in range(9)
                if distances.get(pn[p][m] * 729 + on[o][m]) == distance - 1
            )
            records.append((o << 8) | (distance << 4) | move)
    offsets.append(len(records))
    assert len(records) < 65536
    maximum_bucket = max(b - a for a, b in zip(offsets, offsets[1:]))
    assert maximum_bucket == 11
    tables += [("near_offsets", "half", offsets),
               ("near_records", "word", records)]
    with (ROOT / "src/rubik/solver_tables.S").open("w") as output:
        output.write("/* Generated by tools/rubik/gen_search_tables.py.\n"
                     " * Original source: solver_tables.inc.\n"
                     " * Quarter turns and exact radius-five suffix records.\n"
                     " * Encoding is documented in docs/architecture-progress.md. */\n"
                     "    .section .rodata\n")
        for name, directive, values in tables:
            output.write(f"    .balign 4\n    .globl {name}\n"
                         f"    .type {name}, @object\n{name}:\n")
            for i in range(0, len(values), 12):
                output.write(f"    .{directive} " +
                             ", ".join(map(str, values[i:i + 12])) + "\n")
            output.write(f"    .size {name}, .-{name}\n")
    print("Checked all 51,921 original transitions and all quarter-turn cycles.")
    print(f"Exact suffix records: {len(records)}; maximum bucket: {maximum_bucket}")


if __name__ == "__main__":
    generate()
